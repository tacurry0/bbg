import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {mkdirSync} from 'node:fs';
import {resolve,extname,sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright';
const dir=resolve(fileURLToPath(new URL('../dist/',import.meta.url)));
const mime={'.html':'text/html; charset=utf-8','.js':'text/javascript','.css':'text/css','.json':'application/json','.svg':'image/svg+xml','.webp':'image/webp','.png':'image/png','.glb':'model/gltf-binary','.woff':'font/woff'};
const server=createServer(async(req,res)=>{try{const u=new URL(req.url,'http://localhost'),file=resolve(dir,'.'+(u.pathname==='/'?'/index.html':decodeURIComponent(u.pathname)));if(!file.startsWith(dir+sep)){res.writeHead(403).end();return;}res.writeHead(200,{'Content-Type':mime[extname(file)]||'application/octet-stream','Cache-Control':'no-store'});res.end(await readFile(file));}catch{res.end();}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1,serviceWorkers:'block'});
 const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 const tap=async selector=>{await page.locator(selector).first().tap();};
 const kind=async expected=>{await page.locator('#modal-content[data-kind="'+expected+'"]').waitFor({state:'visible'});};
 const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('nightball.settings')));
 await page.goto('http://127.0.0.1:'+server.address().port+'/',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('[data-mode="match"]')?.onclick);
 await tap('[data-mode="match"]');await kind('setup');
 mkdirSync('tests/screenshots',{recursive:true});
 for(const [width,height] of [[320,568],[390,844],[412,915]]){
  await page.setViewportSize({width,height});
  await page.waitForTimeout(350);
  const fit=await page.evaluate(()=>{const p=document.querySelector('#modal-content'),b=p.querySelector('.pf-body'),f=p.querySelector('.pf-footer'),r=f.getBoundingClientRect(),v=window.visualViewport;return {width:b.scrollWidth<=b.clientWidth+1,footer:r.bottom<=Math.min(innerHeight,v?.height??innerHeight)+1&&r.top>=0,scroll:p.scrollHeight<=p.clientHeight+1,innerHeight,visualHeight:v?.height,footerRect:r.toJSON(),modalRect:p.getBoundingClientRect().toJSON(),backdropRect:document.querySelector('#modal').getBoundingClientRect().toJSON()};});
  await page.screenshot({path:'tests/screenshots/pregame-'+width+'.png'});
  assert(fit.width&&fit.footer&&fit.scroll,JSON.stringify({width,height,fit}));
 }
 await tap('[data-ui-team-side="home"]');await kind('match-teams');
 await tap('[data-match-group="npb"]');assert.equal(await page.locator('[data-match-club]:not([data-match-club="dream"])').count(),14);
 await page.screenshot({path:'tests/screenshots/pregame-teams.png'});
 const club=await page.locator('[data-match-club^="npb-"]').first().getAttribute('data-match-club');
 await tap('[data-match-club="'+club+'"]');await kind('setup');assert.equal((await state()).matchTeam,club);
 await tap('[data-innings="9"]');assert.equal((await state()).innings,9);
 await tap('[data-ui-light="night"]');assert.equal((await state()).gameLighting,'night');
 await tap('[data-action="ui-park-open"]');await kind('park-picker');
 await tap('[data-ui-park-group="npb"]');const park=await page.locator('[data-ui-park]').first().getAttribute('data-ui-park');
 await tap('[data-ui-park="'+park+'"]');await kind('setup');assert.equal((await state()).park,park);
 await tap('[data-action="ui-pitcher-open"]');await kind('match-pitchers');
 assert((await page.locator('[data-ui-pitcher]').count())>1);await page.screenshot({path:'tests/screenshots/pregame-pitchers.png'});
 const pitcher=await page.locator('[data-ui-pitcher]').nth(1).getAttribute('data-ui-pitcher');
 await tap('[data-ui-pitcher="'+pitcher+'"]');await kind('setup');assert.equal((await state()).matchLineups[club].pitcher,Number(pitcher));
 await tap('[data-action="match-lineup"]');await kind('lineup');
 const before=await page.locator('.squad-starter-row [data-editor-player]').evaluateAll(xs=>xs.map(x=>x.dataset.editorPlayer));
 await tap('.squad-starter-row [data-editor-player]');await page.locator('.squad-starter-row [data-editor-player]').nth(1).tap();
 const after=await page.locator('.squad-starter-row [data-editor-player]').evaluateAll(xs=>xs.map(x=>x.dataset.editorPlayer));
 assert.equal(after[0],before[1]);assert.equal(after[1],before[0]);
 await page.screenshot({path:'tests/screenshots/pregame-lineup.png'});
 await tap('.pf-footer [data-action="ui-lineup-done"]');await kind('setup');
 await tap('[data-action="ui-options-open"]');await kind('match-options');await tap('[data-toggle="variantFullCount"]');await kind('match-options');assert.equal((await state()).variantFullCount,true);
 await tap('.pf-footer [data-action="ui-park-back"]');await kind('setup');
 await tap('[data-action="ui-presets-open"]');await kind('match-presets');
 await page.locator('#match-preset-name').fill('Test');await tap('[data-action="match-preset-save"]');await kind('match-presets');
 assert((await page.locator('[data-match-preset]').count())>0);
 await tap('.pf-header [data-action="ui-park-back"]');await kind('setup');
 await tap('[data-action="ui-match-start"]');await page.locator('#game').waitFor({state:'visible',timeout:30000});
 assert.deepEqual(errors,[]);
 console.log('PASS: pregame flow, 320/390/412px layout, persistence, roster swap, settings, presets and launch');
}finally{await browser.close();await new Promise(r=>server.close(r));}
